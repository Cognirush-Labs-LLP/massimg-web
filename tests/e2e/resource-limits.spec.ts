import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { expect, test } from '@playwright/test'

// ImageMagick's resource limits are the backstop for every file the header reader cannot judge, so
// they are tested against the shipped worker rather than the loader in isolation: the budget has to
// arrive through the pool's `configure` message, be applied as ImageMagick initialises, and turn a
// decompression bomb into a per-image failure that leaves the worker usable. The bombs are a few KB
// to tens of KB and declare 324 megapixels (PNG), 9000 frames of a 3000x3000 canvas (GIF) and a
// 16383x16383 lossless WebP; tests/fixtures/limits/ is generated by verification/t50-limits.
const FIXTURE_NAMES = [
  'bomb-18k-area.png',
  'bomb-frames.gif',
  'bomb-webp-16k.webp',
  'gray-6mp.png',
] as const

const POOL_MODULE_PATH = '/src/pipeline/pool.ts'
const LIMITS_MODULE_PATH = '/src/config/limits.ts'

function fixture(name: string): number[] {
  return Array.from(
    readFileSync(fileURLToPath(new URL(`../fixtures/limits/${name}`, import.meta.url))),
  )
}

interface Outcome {
  imageId: string
  outcome: string
  reasonKind: string | undefined
  ms: number
}

// A 6 MP image fits a 512 MiB budget and not a 64 MiB one, so the same bytes tell the two device
// tiers apart without pinning the shipped numbers. Every bomb is far over both.
function runThroughTier(
  page: import('@playwright/test').Page,
  mobile: boolean,
  jobs: { imageId: string; name: (typeof FIXTURE_NAMES)[number]; animated?: boolean }[],
): Promise<Outcome[]> {
  return page.evaluate(
    async ({ poolPath, limitsPath, mobile, jobs, files }) => {
      const { createWorkerPool } = await import(/* @vite-ignore */ poolPath)
      const { runtimeLimits, deriveCodecLimits } = await import(/* @vite-ignore */ limitsPath)
      const MiB = 1024 * 1024
      const pool = createWorkerPool({
        size: 1,
        mobile,
        limits: {
          ...runtimeLimits,
          desktopCodec: deriveCodecLimits(512 * MiB, 500),
          mobileCodec: deriveCodecLimits(64 * MiB, 500),
        },
      })

      const outcomes: Outcome[] = []
      // Sequential, so a later job runs in the worker an earlier bomb has already hit.
      for (const spec of jobs) {
        const started = performance.now()
        const done = await pool.run({
          imageId: spec.imageId,
          source: new Uint8Array(files[spec.name] ?? []),
          edit: null,
          settings: {
            quality: { kind: 'quality', value: 80, lossless: false },
            dimension: { kind: 'original' },
            format: spec.animated ? 'webp' : 'jpeg',
            isAnimated: Boolean(spec.animated),
            sourceFormat: spec.animated ? 'gif' : 'png',
            alpha: { kind: 'preserve' },
          },
          intent: 'preview',
        }).done
        outcomes.push({
          imageId: spec.imageId,
          outcome: done.outcome,
          reasonKind: done.reason?.kind,
          ms: Math.round(performance.now() - started),
        })
      }
      pool.destroy()
      return outcomes
    },
    {
      poolPath: POOL_MODULE_PATH,
      limitsPath: LIMITS_MODULE_PATH,
      mobile,
      jobs,
      files: Object.fromEntries(FIXTURE_NAMES.map((name) => [name, fixture(name)])) as Record<
        string,
        number[]
      >,
    },
  )
}

test('a decompression bomb fails its own image quickly and leaves the worker usable', async ({
  page,
}) => {
  await page.goto('/')

  const outcomes = await runThroughTier(page, false, [
    { imageId: 'area', name: 'bomb-18k-area.png' },
    { imageId: 'webp', name: 'bomb-webp-16k.webp' },
    { imageId: 'frames', name: 'bomb-frames.gif', animated: true },
    { imageId: 'after', name: 'gray-6mp.png' },
  ])

  const byId = Object.fromEntries(outcomes.map((o) => [o.imageId, o]))

  for (const id of ['area', 'webp', 'frames']) {
    expect(byId[id]?.outcome, id).toBe('failed')
    // `out-of-memory` halts the whole run (R-X10 would be violated by one oversized image).
    expect(byId[id]?.reasonKind, id).not.toBe('out-of-memory')
    // A bomb that reached an allocation took seconds or died; a refused one takes milliseconds.
    expect(byId[id]?.ms, id).toBeLessThan(5000)
  }

  expect(byId.after?.outcome).toBe('completed')
})

test('an image exactly at the pixel cap is admitted by the guard as well as by the header check', async ({
  page,
}) => {
  await page.goto('/')

  // gray-6mp.png is 3000 x 2000 = 6,000,000 pixels, and 16 bytes per pixel makes that the cap.
  const [outcome] = await page.evaluate(
    async ({ poolPath, limitsPath, bytes }) => {
      const { createWorkerPool } = await import(/* @vite-ignore */ poolPath)
      const { runtimeLimits, deriveCodecLimits } = await import(/* @vite-ignore */ limitsPath)
      const pool = createWorkerPool({
        size: 1,
        mobile: false,
        limits: { ...runtimeLimits, desktopCodec: deriveCodecLimits(16 * 6_000_000, 500) },
      })
      const done = await pool.run({
        imageId: 'at-cap',
        source: new Uint8Array(bytes),
        edit: null,
        settings: {
          quality: { kind: 'quality', value: 80, lossless: false },
          dimension: { kind: 'original' },
          format: 'jpeg',
          isAnimated: false,
          sourceFormat: 'png',
          alpha: { kind: 'preserve' },
        },
        intent: 'preview',
      }).done
      pool.destroy()
      return [{ outcome: done.outcome, reasonKind: done.reason?.kind }]
    },
    { poolPath: POOL_MODULE_PATH, limitsPath: LIMITS_MODULE_PATH, bytes: fixture('gray-6mp.png') },
  )

  expect(outcome?.outcome).toBe('completed')
})

test('the device class reaches the worker: the same image passes the desktop budget and fails the mobile one', async ({
  page,
}) => {
  await page.goto('/')

  const [desktop] = await runThroughTier(page, false, [{ imageId: 'six', name: 'gray-6mp.png' }])
  const [mobile] = await runThroughTier(page, true, [{ imageId: 'six', name: 'gray-6mp.png' }])

  expect(desktop?.outcome).toBe('completed')
  expect(mobile?.outcome).toBe('failed')
  expect(mobile?.reasonKind).not.toBe('out-of-memory')
})
